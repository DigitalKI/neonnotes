#!/usr/bin/env python3
"""Generate a compact repository map for a Godot project.

This script is intentionally generic: it reads GDScript, scenes, tests, and
project.godot with simple regexes, so it works without Godot or tree-sitter.
It is an orientation aid, not a symbol-accurate index. Use ripgrep for exact
lookups.

Usage:
    python3 tools/repo_map.py                 # print Markdown to stdout
    python3 tools/repo_map.py --write         # write build/repo-map.md
    python3 tools/repo_map.py --write PATH    # write a specific file
    python3 tools/repo_map.py --check docs/architecture.md
        Verify paths mentioned in the module map / coverage section, and warn
        about scripts that are not mentioned anywhere in the architecture doc.

Exit codes: 0 = ok, 1 = missing paths referenced by the architecture doc.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

CLASS_RE = re.compile(r"^class_name\s+([A-Za-z_]\w*)", re.M)
EXTENDS_RE = re.compile(r"^extends\s+([A-Za-z_][\w.]*)", re.M)
SIGNAL_RE = re.compile(r"^signal\s+([A-Za-z_]\w*)", re.M)
FUNC_RE = re.compile(r"^(?:static\s+)?func\s+([A-Za-z_]\w*)\s*\(", re.M)
NODE_RE = re.compile(r'^\[node name="([^"]+)"(?: type="([^"]*)")?', re.M)
SCRIPT_RES_RE = re.compile(r'^\[ext_resource[^\]]*type="Script"[^\]]*path="([^"]+)"', re.M)
RESULT_RE = re.compile(r"RESULT(?::\s*[A-Za-z ]+)?")
BACKTICK_RE = re.compile(r"`([^`]+)`")


def read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def project_info(root: Path) -> dict:
    text = read_text(root / "project.godot")
    info = {"name": "", "main_scene": "", "autoloads": [], "godot": ""}
    m = re.search(r'config/name="([^"]*)"', text)
    if m:
        info["name"] = m.group(1)
    m = re.search(r'run/main_scene="([^"]*)"', text)
    if m:
        info["main_scene"] = m.group(1)
    features = re.search(r'config/features=PackedStringArray\(([^)]*)\)', text)
    if features:
        info["godot"] = features.group(1).strip()
    autoload = re.search(r"^\[autoload\]\s*$(.*?)(?=^\[|\Z)", text, re.M | re.S)
    if autoload:
        for line in autoload.group(1).splitlines():
            line = line.strip()
            if line and not line.startswith(";"):
                info["autoloads"].append(line.split("=")[0].strip())
    return info


def gd_info(path: Path, root: Path) -> dict:
    text = read_text(path)
    funcs = FUNC_RE.findall(text)
    return {
        "path": path.relative_to(root).as_posix(),
        "class_name": (CLASS_RE.search(text).group(1) if CLASS_RE.search(text) else ""),
        "extends": (EXTENDS_RE.search(text).group(1) if EXTENDS_RE.search(text) else ""),
        "lines": text.count("\n") + (1 if text and not text.endswith("\n") else 0),
        "functions": len(funcs),
        "public_functions": len([f for f in funcs if not f.startswith("_")]),
        "signals": SIGNAL_RE.findall(text),
    }


def tscn_info(path: Path, root: Path) -> dict:
    text = read_text(path)
    nodes = NODE_RE.findall(text)
    scripts = SCRIPT_RES_RE.findall(text)
    root_name = nodes[0][0] if nodes else ""
    root_type = nodes[0][1] if nodes else ""
    return {
        "path": path.relative_to(root).as_posix(),
        "root": root_name,
        "type": root_type,
        "nodes": len(nodes),
        "scripts": scripts,
    }


def result_marker(path: Path) -> str:
    text = read_text(path)
    m = RESULT_RE.search(text)
    return m.group(0).strip() if m else ""


def collect(root: Path) -> dict:
    scripts = sorted((root / "scripts").rglob("*.gd"))
    scenes = sorted((root / "scenes").rglob("*.tscn"))
    tests = sorted((root / "tests").glob("*.gd")) + sorted((root / "tests").glob("*.tscn"))
    return {
        "project": project_info(root),
        "scripts": [gd_info(p, root) for p in scripts],
        "scenes": [tscn_info(p, root) for p in scenes],
        "tests": [
            {
                "path": p.relative_to(root).as_posix(),
                "marker": result_marker(p),
            }
            for p in tests
        ],
    }


def render_markdown(data: dict) -> str:
    p = data["project"]
    out = ["# Repository map (generated)", ""]
    out.append("_Generated by `tools/repo_map.py`. Do not edit; regenerate when the")
    out.append("tree changes. This is an orientation aid, not a symbol index._")
    out.append("")
    out.append("## Project")
    out.append("")
    if p["name"]:
        out.append(f"- Name: `{p['name']}`")
    if p["godot"]:
        out.append(f"- Godot features: `{p['godot']}`")
    if p["main_scene"]:
        out.append(f"- Main scene: `{p['main_scene']}`")
    if p["autoloads"]:
        out.append("- Autoloads: " + ", ".join(f"`{a}`" for a in p["autoloads"]))
    out.append(f"- Scripts: {len(data['scripts'])} · Scenes: {len(data['scenes'])} · Test files: {len(data['tests'])}")
    out.append("")

    out.append("## Scripts")
    out.append("")
    out.append("| Path | class_name | extends | lines | funcs | public | signals |")
    out.append("|---|---|---|---:|---:|---:|---|")
    for s in data["scripts"]:
        out.append(
            f"| `{s['path']}` | {('`' + s['class_name'] + '`') if s['class_name'] else ''} "
            f"| {('`' + s['extends'] + '`') if s['extends'] else ''} "
            f"| {s['lines']} | {s['functions']} | {s['public_functions']} "
            f"| {', '.join('`' + x + '`' for x in s['signals'][:6])} |"
        )
    out.append("")

    out.append("## Scenes")
    out.append("")
    out.append("| Path | root | type | nodes | scripts |")
    out.append("|---|---|---|---:|---|")
    for s in data["scenes"]:
        out.append(
            f"| `{s['path']}` | {s['root']} | {s['type']} | {s['nodes']} "
            f"| {', '.join('`' + x + '`' for x in s['scripts']) or ''} |"
        )
    out.append("")

    out.append("## Tests")
    out.append("")
    out.append("| Path | result marker |")
    out.append("|---|---|")
    for t in data["tests"]:
        out.append(f"| `{t['path']}` | {t['marker'] or ''} |")
    out.append("")
    return "\n".join(out)


def check(root: Path, arch_path: Path) -> int:
    if not arch_path.is_file():
        print(f"error: {arch_path} does not exist", file=sys.stderr)
        return 1
    text = read_text(arch_path)
    errors: list[str] = []

    # Paths in the first column of Markdown tables are the module map.
    module_paths = []
    for line in text.splitlines():
        if not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if not cells:
            continue
        m = re.fullmatch(r"`([^`]+)`", cells[0])
        if m:
            module_paths.append(m.group(1))

    for rel in module_paths:
        if "*" in rel or "?" in rel:
            continue
        target = root / rel
        if not target.exists():
            errors.append(f"module map path does not exist: {rel}")

    # Coverage directories are listed after the "## 8. Coverage" heading.
    coverage = text.split("## 8. Coverage", 1)
    if len(coverage) == 2:
        for token in BACKTICK_RE.findall(coverage[1]):
            # Backticks may hold a command (e.g. `tools/repo_map.py --check`);
            # the coverage path is the first token.
            token = token.split()[0] if token.split() else token
            if token.startswith(("http", "res://", "user://")):
                continue
            if "*" in token:
                continue
            target = root / token
            if not target.exists():
                errors.append(f"coverage path does not exist: {token}")

    # Warn about scripts not mentioned anywhere in the architecture doc.
    data = collect(root)
    mentioned = set()
    for token in BACKTICK_RE.findall(text):
        if token.startswith(("res://", "user://")):
            continue
        mentioned.add(token.strip("`"))
    unmentioned = []
    for s in data["scripts"]:
        rel = s["path"]
        parent = rel.rsplit("/", 1)[0]
        if rel not in mentioned and parent not in mentioned:
            unmentioned.append(rel)

    if errors:
        for e in errors:
            print(f"error: {e}", file=sys.stderr)
    if unmentioned:
        print("warning: scripts not mentioned in the architecture map:", file=sys.stderr)
        for rel in unmentioned[:20]:
            print(f"  - {rel}", file=sys.stderr)
        if len(unmentioned) > 20:
            print(f"  ... and {len(unmentioned) - 20} more", file=sys.stderr)
    print(
        f"checked {len(module_paths)} module paths, "
        f"{len(data['scripts'])} scripts ({len(unmentioned)} unmentioned)"
    )
    return 1 if errors else 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default=".", help="project root (default: cwd)")
    parser.add_argument("--write", nargs="?", const="build/repo-map.md", help="write Markdown to a file")
    parser.add_argument("--check", metavar="ARCH_DOC", help="check an architecture doc's paths")
    args = parser.parse_args()

    root = Path(args.root).resolve()
    if not (root / "project.godot").is_file():
        print(f"error: no project.godot under {root}", file=sys.stderr)
        return 1

    if args.check:
        return check(root, (root / args.check).resolve())

    markdown = render_markdown(collect(root))
    if args.write:
        out = root / args.write
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(markdown, encoding="utf-8")
        print(f"wrote {out.relative_to(root)}")
    else:
        print(markdown)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
